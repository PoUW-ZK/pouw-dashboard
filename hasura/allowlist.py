"""Allow-list of the web API: every operation of the contract, nothing else (pouw-dashboard#47).

Hasura runs with HASURA_GRAPHQL_ENABLE_ALLOWLIST=true (hasura/Dockerfile), so a request
without the admin secret (role anonymous) runs only if its document is in
hasura/metadata/query_collections.yaml. This script writes that file from the contract:

    python hasura/allowlist.py [path/to/web-api.graphql]

default contract: ../pouw-docs/contracts/web-api.graphql, or WEB_API_GRAPHQL.
Run it after every change of the contract and commit the result; the query tests
(hasura/tests/test_allowlist.py) fail while the file and the contract differ.

One entry is one document: an operation followed by the fragments it uses. A client must
send exactly this document (whitespace and __typename do not matter, the order of fields
does). A live-query subscription (HomeStats, LatestBlocks) also gets a query twin
("<name>AsQuery"), because over HTTP the same selection is sent as a query.
"""

import copy
import os
import sys
from pathlib import Path

from graphql import OperationType, parse, print_ast
from graphql.language import (
    DocumentNode,
    FragmentDefinitionNode,
    FragmentSpreadNode,
    OperationDefinitionNode,
    Visitor,
    visit,
)

HASURA = Path(__file__).resolve().parent
COLLECTIONS = HASURA / "metadata" / "query_collections.yaml"
COLLECTION = "web-api"
DEFAULT_CONTRACT = Path(
    os.environ.get(
        "WEB_API_GRAPHQL", HASURA.parent.parent / "pouw-docs" / "contracts" / "web-api.graphql"
    )
)


def is_stream(op: OperationDefinitionNode) -> bool:
    """A streaming subscription (root field *_stream), sent only over WebSocket."""
    return any(
        getattr(sel, "name", None) and sel.name.value.endswith("_stream")
        for sel in op.selection_set.selections
    )


def operation_text(op: OperationDefinitionNode, fragments: dict) -> str:
    """The operation followed by the fragments it uses, in the order they are first used."""
    needed, todo = {}, [op]
    while todo:
        spreads = []

        class Spreads(Visitor):
            def enter_fragment_spread(self, node: FragmentSpreadNode, *_):
                spreads.append(node.name.value)

        visit(todo.pop(), Spreads())
        for s in spreads:
            if s not in needed:
                needed[s] = fragments[s]
                todo.append(fragments[s])
    return print_ast(DocumentNode(definitions=[op, *needed.values()]))


def as_query(op: OperationDefinitionNode) -> OperationDefinitionNode:
    twin = copy.deepcopy(op)
    twin.operation = OperationType.QUERY
    return twin


def entries(contract_text: str) -> dict[str, str]:
    """name in the collection -> document, for every operation of the contract."""
    doc = parse(contract_text)
    fragments = {
        d.name.value: d for d in doc.definitions if isinstance(d, FragmentDefinitionNode)
    }
    result = {}
    for op in doc.definitions:
        if not isinstance(op, OperationDefinitionNode):
            continue
        name = op.name.value
        result[name] = operation_text(op, fragments)
        if op.operation == OperationType.SUBSCRIPTION and not is_stream(op):
            result[name + "AsQuery"] = operation_text(as_query(op), fragments)
    return result


def render(contract_text: str) -> str:
    """query_collections.yaml, written by hand so that the file is stable and readable."""
    lines = [
        "# Generated by hasura/allowlist.py from pouw-docs/contracts/web-api.graphql.",
        "# Do not edit: change the contract and run python hasura/allowlist.py",
        f"- name: {COLLECTION}",
        "  definition:",
        "    queries:",
    ]
    for name, text in entries(contract_text).items():
        lines.append(f"      - name: {name}")
        lines.append("        query: |")
        lines.extend(("          " + line).rstrip() for line in text.splitlines())
    return "\n".join(lines) + "\n"


def main() -> int:
    contract = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CONTRACT
    if not contract.is_file():
        print(f"contract not found: {contract}", file=sys.stderr)
        return 2
    text = render(contract.read_text(encoding="utf-8"))
    COLLECTIONS.write_text(text, encoding="utf-8")
    print(f"{COLLECTIONS.relative_to(HASURA.parent)}: {text.count('- name: ') - 1} operations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
